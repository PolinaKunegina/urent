def guide_requests(sheet_id: int) -> list[dict]:
    def row_fmt(i, bold, size, top_pad):
        return {"repeatCell": {
            "range": {"sheetId": sheet_id, "startRowIndex": i, "endRowIndex": i + 1,
                      "startColumnIndex": 0, "endColumnIndex": 1},
            "cell": {"userEnteredFormat": {"textFormat": {"bold": bold, "fontSize": size},
                                           "wrapStrategy": "WRAP", "verticalAlignment": "TOP",
                                           "padding": {"top": top_pad, "bottom": 4, "left": 6, "right": 6}}},
            "fields": "userEnteredFormat(textFormat,wrapStrategy,verticalAlignment,padding)"}}

    reqs = [{"updateDimensionProperties": {"range": {"sheetId": sheet_id, "dimension": "COLUMNS",
                                                     "startIndex": 0, "endIndex": 1},
                                           "properties": {"pixelSize": 820}, "fields": "pixelSize"}},
            {"updateSheetProperties": {"properties": {"sheetId": sheet_id, "gridProperties": {
                "hideGridlines": True}}, "fields": "gridProperties.hideGridlines"}}]
    for i, (style, _) in enumerate(GUIDE):
        if style == "title":
            reqs.append(row_fmt(i, True, 16, 8))
        elif style == "h":
            reqs.append(row_fmt(i, True, 12, 14))
        else:
            reqs.append(row_fmt(i, False, 11, 2))
    return reqs


